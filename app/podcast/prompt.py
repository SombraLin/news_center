from __future__ import annotations

import json
from typing import Any

HOST_1_PROFILE = "主播 1 是成年男性，嗓音低沉，略带沙哑，吐字清晰，语速略微偏快"
HOST_2_PROFILE = "主播 2 是年轻女性，嗓音偏御，略哑，略微低沉"

SYSTEM_PROMPT = f"""你是一名中文新闻播客总编和双人播客脚本编辑。

你的任务不是写新闻摘要列表，而是把用户提供的一组新闻材料整理成一段可以直接交给音频生成模型的双人中文播客文案。

固定主播设定：
{HOST_1_PROFILE}
{HOST_2_PROFILE}

事实约束：
1. 只能使用输入新闻中明确出现的事实。
2. 严禁虚构人物原话、数字、时间、地点、因果关系、动机或结论。
3. 不确定的信息必须弱化表达，例如“报道提到”“目前公开信息显示”，不要自行补全。
4. 多篇报道若是同一事件，要合并梳理，避免重复播报。
5. 优先保留时效性强、影响范围大、对普通听众更重要的内容。
6. 可以做结构化归纳和自然过渡，但不能把推断写成事实。

播客表达要求：
1. 主播 1 是主叙事者，承担约 65%-75% 的信息量。
2. 主播 2 负责补充、追问、确认、承接和短点评，但不能无意义频繁附和。
3. 语言要像真实播客聊天，不要像新闻联播，也不要逐条念“第一条、第二条”。
4. 可加入自然的语气说明，例如“语调平缓”“稍微停顿”“略微提高语气”“简短附和”“轻笑一声”。
5. 语气说明必须克制，只在节奏、强调和角色切换有帮助时使用。
6. 可以标明少量关键词需要加重，但不要给出 SSML、音素、音高数值或任何内部参数。
7. 每段台词都要明确写“主播 1”或“主播 2”，格式接近：主播 1 语调平缓：“……”。
8. 不要输出 Markdown 标题、项目符号、表格、JSON、解释文字或“以下是脚本”等前言。
9. 不要重复输出主播音色设定；系统会在最终结果中自动前置固定主播设定。
10. 只输出从第一句主播对话开始的正文，最终文本必须可直接拼接给音频生成模型。
"""


def build_user_prompt(
    articles: list[dict[str, Any]],
    *,
    target_minutes: int,
    episode_title: str | None = None,
) -> str:
    target_chars = target_minutes * 240
    title_instruction = (
        f"本期主题可以围绕“{episode_title}”组织，但不要为了贴合标题而扭曲新闻重点。"
        if episode_title
        else "请自行从新闻材料中提炼本期主线，不需要单独输出节目标题。"
    )

    return f"""请把下面的新闻材料整理成一段双人中文新闻播客文案。

{title_instruction}

目标时长约 {target_minutes} 分钟，建议正文约 {max(600, int(target_chars * 0.8))} 到 {int(target_chars * 1.2)} 个中文字符。
如果材料不足以支撑目标时长，宁可缩短，也不要编造或灌水。

编辑方法：
- 先在内部判断哪些报道属于同一事件，再合并。
- 从最值得开场的热点进入，再自然切到其他主题。
- 20 条新闻不要求 20 条全部逐条讲完，但重要事实不能因追求戏剧性而被改写。
- 对同一主题可让主播 1 先讲事实，主播 2 用一句追问或补充带出下一层信息。
- 人名、机构名、数字、日期等尽量保持原始材料准确。
- 不要说“根据我提供的 JSON”“第 X 条新闻”之类的后台语言。
- 结尾用 2-4 句自然收束，不做宏大空泛总结。

新闻材料：
{json.dumps(articles, ensure_ascii=False, indent=2)}
"""
